from __future__ import annotations
from typing import Protocol, runtime_checkable
"""Notification storage backends.

Notifications are generated by the sync daemon when a bookmarked table is
modified (TABLE_DESC, COLUMN_DEF, STEWARD sync types succeed). Each
bookmarker of that table gets an unread row here; the Streamlit UI reads
and dismisses them.

Backends:
  DemoNotificationStorage  — session-state list; no persistence across reloads
  DuckDBNotificationStorage — user_data.notifications (persistent)
  FakeNotificationStorage   — in-memory dict; for unit tests
"""

import logging
from datetime import datetime, timezone

log = logging.getLogger(__name__)


@runtime_checkable
class NotificationStorage(Protocol):
    def create(
        self,
        notification_id: str,
        user_oid: str,
        table_full_name: str,
        change_type: str,
        changed_by: str,
        summary: str,
    ) -> None: ...

    def list_unread(self, user_oid: str, limit: int = 20) -> list[dict]: ...
    def mark_read(self, notification_id: str) -> None: ...
    def mark_all_read(self, user_oid: str) -> None: ...


# ── Demo backend ──────────────────────────────────────────────────────────────

class DemoNotificationStorage:
    """Session-state backed notifications for demo/mock-auth mode."""

    _KEY = "_demo_notifications"

    def _store(self):
        import streamlit as st
        if self._KEY not in st.session_state:
            st.session_state[self._KEY] = []
        return st.session_state[self._KEY]

    def create(self, notification_id, user_oid, table_full_name, change_type, changed_by, summary):
        self._store().append({
            "notification_id": notification_id,
            "user_oid": user_oid,
            "table_full_name": table_full_name,
            "change_type": change_type,
            "changed_by": changed_by,
            "summary": summary,
            "created_at": datetime.now(timezone.utc).replace(tzinfo=None),
            "read_at": None,
        })

    def list_unread(self, user_oid: str, limit: int = 20) -> list[dict]:
        return [
            n for n in reversed(self._store())
            if n["user_oid"] == user_oid and n["read_at"] is None
        ][:limit]

    def mark_read(self, notification_id: str) -> None:
        now = datetime.now(timezone.utc).replace(tzinfo=None)
        for n in self._store():
            if n["notification_id"] == notification_id:
                n["read_at"] = now
                return

    def mark_all_read(self, user_oid: str) -> None:
        now = datetime.now(timezone.utc).replace(tzinfo=None)
        for n in self._store():
            if n["user_oid"] == user_oid and n["read_at"] is None:
                n["read_at"] = now


# ── DuckDB backend ────────────────────────────────────────────────────────────

class DuckDBNotificationStorage:
    def create(self, notification_id, user_oid, table_full_name, change_type, changed_by, summary):
        try:
            from src.db.duckdb_adapter import _db_write_lock
            from src.db.queries import _get_write_connection
            conn = _get_write_connection()
            with _db_write_lock:
                conn.execute(
                    """
                    INSERT INTO user_data.notifications
                        (notification_id, user_oid, table_full_name, change_type,
                         changed_by, summary, created_at)
                    VALUES (?, ?, ?, ?, ?, ?, ?)
                    """,
                    [
                        notification_id, user_oid, table_full_name,
                        change_type, changed_by, summary,
                        datetime.now(timezone.utc).replace(tzinfo=None),
                    ],
                )
        except Exception as exc:
            log.warning("Could not create notification %s: %s", notification_id, exc)

    def list_unread(self, user_oid: str, limit: int = 20) -> list[dict]:
        try:
            from src.db.queries import get_db_connection
            conn = get_db_connection()
            with conn.cursor() as cur:
                cur.execute(
                    """
                    SELECT notification_id, table_full_name, change_type,
                           changed_by, summary, created_at
                    FROM user_data.notifications
                    WHERE user_oid = ? AND read_at IS NULL
                    ORDER BY created_at DESC
                    LIMIT ?
                    """,
                    [user_oid, limit],
                )
                rows = cur.fetchall()
            return [
                {
                    "notification_id": r[0],
                    "table_full_name": r[1],
                    "change_type": r[2],
                    "changed_by": r[3],
                    "summary": r[4],
                    "created_at": r[5],
                }
                for r in (rows or [])
            ]
        except Exception as exc:
            log.warning("Could not list notifications for %s: %s", user_oid, exc)
            return []

    def mark_read(self, notification_id: str) -> None:
        try:
            from src.db.duckdb_adapter import _db_write_lock
            from src.db.queries import _get_write_connection
            conn = _get_write_connection()
            with _db_write_lock:
                conn.execute(
                    "UPDATE user_data.notifications SET read_at = ? WHERE notification_id = ?",
                    [datetime.now(timezone.utc).replace(tzinfo=None), notification_id],
                )
        except Exception as exc:
            log.warning("Could not mark notification %s read: %s", notification_id, exc)

    def mark_all_read(self, user_oid: str) -> None:
        try:
            from src.db.duckdb_adapter import _db_write_lock
            from src.db.queries import _get_write_connection
            conn = _get_write_connection()
            with _db_write_lock:
                conn.execute(
                    "UPDATE user_data.notifications SET read_at = ? "
                    "WHERE user_oid = ? AND read_at IS NULL",
                    [datetime.now(timezone.utc).replace(tzinfo=None), user_oid],
                )
        except Exception as exc:
            log.warning("Could not mark all notifications read for %s: %s", user_oid, exc)


# ── Fake backend (tests) ──────────────────────────────────────────────────────

class FakeNotificationStorage:
    """In-memory backend for unit tests — no Streamlit dependency."""

    def __init__(self) -> None:
        self._rows: list[dict] = []

    def create(self, notification_id, user_oid, table_full_name, change_type, changed_by, summary):
        self._rows.append({
            "notification_id": notification_id,
            "user_oid": user_oid,
            "table_full_name": table_full_name,
            "change_type": change_type,
            "changed_by": changed_by,
            "summary": summary,
            "created_at": datetime.now(timezone.utc).replace(tzinfo=None),
            "read_at": None,
        })

    def list_unread(self, user_oid: str, limit: int = 20) -> list[dict]:
        return [
            {k: v for k, v in r.items() if k != "user_oid" and k != "read_at"}
            for r in reversed(self._rows)
            if r["user_oid"] == user_oid and r["read_at"] is None
        ][:limit]

    def mark_read(self, notification_id: str) -> None:
        now = datetime.now(timezone.utc).replace(tzinfo=None)
        for r in self._rows:
            if r["notification_id"] == notification_id:
                r["read_at"] = now
                return

    def mark_all_read(self, user_oid: str) -> None:
        now = datetime.now(timezone.utc).replace(tzinfo=None)
        for r in self._rows:
            if r["user_oid"] == user_oid and r["read_at"] is None:
                r["read_at"] = now
